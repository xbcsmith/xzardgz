/// Capability flags and context-window size for a single AI model.
///
/// Unlike [`ProviderCapabilities`], which reflects provider-level aggregates,
/// this struct captures per-model accuracy and is used by the model resolver
/// during selection and thinking-mode resolution.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::ModelCapabilities;
///
/// let caps = ModelCapabilities::default();
/// assert!(!caps.supports_tools);
/// assert_eq!(caps.context_window_tokens, 4096);
/// ```
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModelCapabilities {
    /// Whether this model supports tool/function calling.
    pub supports_tools: bool,
    /// Whether this model supports structured output (e.g., JSON schema enforcement).
    pub supports_structured_output: bool,
    /// Whether this model supports extended chain-of-thought reasoning.
    pub supports_thinking: bool,
    /// Whether this model supports streaming response delivery.
    pub supports_streaming: bool,
    /// Whether this model accepts image inputs (vision).
    pub supports_vision: bool,
    /// Approximate context window size in tokens.
    pub context_window_tokens: u32,
}

impl Default for ModelCapabilities {
    /// Returns conservative defaults: all capabilities disabled, 4,096-token
    /// context window.
    fn default() -> Self {
        Self {
            supports_tools: false,
            supports_structured_output: false,
            supports_thinking: false,
            supports_streaming: false,
            supports_vision: false,
            context_window_tokens: 4096,
        }
    }
}

/// Full metadata record for a single AI model.
///
/// Holds the model's provider-assigned identifier, an optional human-readable
/// display name, and its capability flags.  Used by the model resolver during
/// selection and thinking-mode resolution.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::{ModelCapabilities, ModelMetadata};
///
/// let caps = ModelCapabilities::default();
/// let meta = ModelMetadata::new("gpt-4o-mini", caps);
/// assert_eq!(meta.id, "gpt-4o-mini");
/// assert_eq!(meta.display_name, Some("gpt-4o-mini".to_string()));
/// ```
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModelMetadata {
    /// Provider-assigned model identifier (e.g., `"gpt-4o-mini"`).
    pub id: String,
    /// Optional human-readable display name shown in UI and reports.
    pub display_name: Option<String>,
    /// Capability flags for this specific model.
    pub capabilities: ModelCapabilities,
}

impl ModelMetadata {
    /// Constructs a `ModelMetadata` with `display_name` initialised equal to `id`.
    ///
    /// # Arguments
    ///
    /// * `id` - The provider-assigned model identifier.
    /// * `capabilities` - The capability flags for this model.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::{ModelCapabilities, ModelMetadata};
    ///
    /// let meta = ModelMetadata::new("claude-3-5-sonnet", ModelCapabilities::default());
    /// assert_eq!(meta.id, "claude-3-5-sonnet");
    /// assert_eq!(meta.display_name, Some("claude-3-5-sonnet".to_string()));
    /// ```
    pub fn new(id: impl Into<String>, capabilities: ModelCapabilities) -> Self {
        let id = id.into();
        let display_name = Some(id.clone());
        Self {
            id,
            display_name,
            capabilities,
        }
    }
}

