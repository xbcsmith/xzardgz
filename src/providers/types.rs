/// Thinking/reasoning mode for AI providers that support extended reasoning.
///
/// Controls whether and how deeply a provider should "think" (chain-of-thought
/// reasoning) before composing a final response.  The resolver maps `Auto` to
/// a concrete level at runtime based on model capabilities.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::ThinkingMode;
///
/// assert!(!ThinkingMode::None.requests_thinking());
/// assert!(ThinkingMode::Low.requests_thinking());
/// assert!(ThinkingMode::Low.requires_thinking_support());
/// assert!(!ThinkingMode::Auto.requires_thinking_support());
/// assert_eq!(ThinkingMode::Medium.budget_tokens(), Some(8_000));
/// assert_eq!(ThinkingMode::None.budget_tokens(), None);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum ThinkingMode {
    /// Never perform any extended reasoning; respond directly.
    #[default]
    None,
    /// Use extended reasoning if the model supports it; skip silently if not.
    Auto,
    /// Request approximately 2,000 tokens of reasoning budget.
    Low,
    /// Request approximately 8,000 tokens of reasoning budget.
    Medium,
    /// Request approximately 16,000 tokens of reasoning budget.
    High,
    /// Request approximately 32,000 tokens of reasoning budget.
    ExtraHigh,
}

impl ThinkingMode {
    /// Returns `true` if this mode requests any form of thinking.
    ///
    /// Both `Auto` and all explicit levels return `true`.  Only `None` returns
    /// `false`.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::ThinkingMode;
    ///
    /// assert!(!ThinkingMode::None.requests_thinking());
    /// assert!(ThinkingMode::Auto.requests_thinking());
    /// assert!(ThinkingMode::High.requests_thinking());
    /// ```
    pub fn requests_thinking(&self) -> bool {
        !matches!(self, Self::None)
    }

    /// Returns `true` if an explicit thinking level was requested.
    ///
    /// Explicit levels (`Low`, `Medium`, `High`, `ExtraHigh`) indicate the
    /// caller expects full thinking support from the selected model.  `None`
    /// and `Auto` return `false` — they either opt-out or degrade gracefully.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::ThinkingMode;
    ///
    /// assert!(ThinkingMode::Low.requires_thinking_support());
    /// assert!(ThinkingMode::ExtraHigh.requires_thinking_support());
    /// assert!(!ThinkingMode::Auto.requires_thinking_support());
    /// assert!(!ThinkingMode::None.requires_thinking_support());
    /// ```
    pub fn requires_thinking_support(&self) -> bool {
        matches!(
            self,
            Self::Low | Self::Medium | Self::High | Self::ExtraHigh
        )
    }

    /// Returns the approximate token budget for providers that accept a budget.
    ///
    /// Returns `None` for [`ThinkingMode::None`] and [`ThinkingMode::Auto`],
    /// indicating the caller or provider should choose the budget.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::ThinkingMode;
    ///
    /// assert_eq!(ThinkingMode::None.budget_tokens(), None);
    /// assert_eq!(ThinkingMode::Auto.budget_tokens(), None);
    /// assert_eq!(ThinkingMode::Low.budget_tokens(), Some(2_000));
    /// assert_eq!(ThinkingMode::Medium.budget_tokens(), Some(8_000));
    /// assert_eq!(ThinkingMode::High.budget_tokens(), Some(16_000));
    /// assert_eq!(ThinkingMode::ExtraHigh.budget_tokens(), Some(32_000));
    /// ```
    pub fn budget_tokens(&self) -> Option<u32> {
        match self {
            Self::None | Self::Auto => None,
            Self::Low => Some(2_000),
            Self::Medium => Some(8_000),
            Self::High => Some(16_000),
            Self::ExtraHigh => Some(32_000),
        }
    }
}

