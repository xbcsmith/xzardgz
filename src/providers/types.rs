//! Core data types for the provider abstraction layer.
//!
//! This module defines the message, tool, capability, and metadata types shared
//! by all AI provider backends, as well as the extended thinking-mode and model
//! capability types introduced in Phase 9.
//!
//! # Type Hierarchy
//!
//! - [`Role`] / [`Message`] — conversation primitives
//! - [`Tool`] / [`ToolCall`] / [`FunctionCall`] — tool-calling support
//! - [`ProviderMetadata`] / [`ProviderCapabilities`] — provider-level aggregates
//! - [`ModelMetadata`] / [`ModelCapabilities`] — per-model capability records
//! - [`ThinkingMode`] — reasoning budget control
//! - [`CredentialStatus`] / [`MetadataSource`] — resolution metadata

use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// Conversation primitives
// ---------------------------------------------------------------------------

/// Role of a message participant in a conversation thread.
///
/// Matches the role taxonomy used by OpenAI-compatible chat completion APIs.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::Role;
///
/// let role = Role::User;
/// assert_eq!(role, Role::User);
/// assert_ne!(role, Role::Assistant);
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum Role {
    /// A system-level instruction message that sets model behavior.
    System,
    /// A message originating from the human user.
    User,
    /// A response generated by the AI assistant.
    Assistant,
    /// A tool invocation result message sent back to the model.
    Tool,
}

/// A single message in a conversation thread.
///
/// Messages form an ordered list passed to the provider for chat completion.
/// Use the [`Message::system`], [`Message::user`], and [`Message::assistant`]
/// constructors for the common cases.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::{Message, Role};
///
/// let msg = Message::user("Explain Rust lifetimes.");
/// assert_eq!(msg.role, Role::User);
/// assert_eq!(msg.content, "Explain Rust lifetimes.");
/// assert!(msg.name.is_none());
/// assert!(msg.tool_calls.is_none());
/// ```
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// The role of the message author.
    pub role: Role,
    /// The textual content of the message.
    pub content: String,
    /// Optional display name for the author (useful in multi-participant chats).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// Tool calls requested by the assistant in this message, if any.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,
    /// Tool call ID when this message is a tool result, correlating with a
    /// prior [`ToolCall`] from the assistant.
    pub tool_call_id: Option<String>,
}

impl Message {
    /// Creates a new [`Role::System`] message.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::{Message, Role};
    ///
    /// let msg = Message::system("You are a helpful assistant.");
    /// assert_eq!(msg.role, Role::System);
    /// assert_eq!(msg.content, "You are a helpful assistant.");
    /// ```
    pub fn system(content: impl Into<String>) -> Self {
        Self {
            role: Role::System,
            content: content.into(),
            name: None,
            tool_calls: None,
            tool_call_id: None,
        }
    }

    /// Creates a new [`Role::User`] message.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::{Message, Role};
    ///
    /// let msg = Message::user("Hello, world!");
    /// assert_eq!(msg.role, Role::User);
    /// assert_eq!(msg.content, "Hello, world!");
    /// ```
    pub fn user(content: impl Into<String>) -> Self {
        Self {
            role: Role::User,
            content: content.into(),
            name: None,
            tool_calls: None,
            tool_call_id: None,
        }
    }

    /// Creates a new [`Role::Assistant`] message.
    ///
    /// # Examples
    ///
    /// ```
    /// use xzardgz::providers::types::{Message, Role};
    ///
    /// let msg = Message::assistant("I can help with that.");
    /// assert_eq!(msg.role, Role::Assistant);
    /// assert_eq!(msg.content, "I can help with that.");
    /// ```
    pub fn assistant(content: impl Into<String>) -> Self {
        Self {
            role: Role::Assistant,
            content: content.into(),
            name: None,
            tool_calls: None,
            tool_call_id: None,
        }
    }
}

