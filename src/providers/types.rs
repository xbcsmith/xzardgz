/// Aggregate metadata describing an AI provider backend.
///
/// Returned by [`Provider::metadata`][crate::providers::base::Provider::metadata]
/// to describe the provider's identity and aggregate capabilities.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProviderMetadata {
    /// The canonical name of this provider (e.g., `"openai"`, `"ollama"`).
    pub name: String,
    /// List of model identifiers available from this provider.
    pub models: Vec<String>,
    /// Aggregate capability flags across all models on this provider.
    pub capabilities: ProviderCapabilities,
}

/// Provider-level capability flags.
///
/// Represents the aggregate capabilities advertised by the provider as a
/// whole. For per-model accuracy use [`ModelCapabilities`] instead.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProviderCapabilities {
    /// Whether any model on this provider supports streaming responses.
    pub streaming: bool,
    /// Whether any model on this provider supports tool/function calling.
    pub tools: bool,
    /// Whether any model on this provider supports vision (image) inputs.
    pub vision: bool,
}

