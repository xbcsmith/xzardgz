/// Credential presence status for a provider.
///
/// Reflects whether credentials are available without making any network
/// calls to validate them against the provider API.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::CredentialStatus;
///
/// let status = CredentialStatus::Present;
/// assert_eq!(status, CredentialStatus::Present);
/// assert_ne!(status, CredentialStatus::Missing);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum CredentialStatus {
    /// Credentials found in env var or keyring. Not validated against the API.
    Present,
    /// No credentials found in any configured location.
    Missing,
    /// Credential status cannot be determined (e.g., keyring service unavailable).
    Unknown,
}

/// Source of model capability metadata used during resolution.
///
/// Records the provenance of [`ModelMetadata`] in a `ResolvedModel` for
/// observability and debugging purposes.
///
/// # Examples
///
/// ```
/// use xzardgz::providers::types::MetadataSource;
///
/// assert_eq!(MetadataSource::Static, MetadataSource::Static);
/// assert_ne!(MetadataSource::Remote, MetadataSource::Degraded);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum MetadataSource {
    /// Metadata fetched live from the provider API.
    Remote,
    /// Metadata from compiled-in static tables.
    Static,
    /// Metadata is incomplete or stale; execution continues in degraded mode.
    Degraded,
}

