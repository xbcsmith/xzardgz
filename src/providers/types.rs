/// A tool call requested by the assistant within a message.
///
/// Each call has a unique `id` that must be included in the corresponding
/// tool result message to allow the model to correlate responses.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
    /// Unique identifier for this tool call instance.
    pub id: String,
    /// The function invocation details for this call.
    pub function: FunctionCall,
}

/// Details of a function invocation within a [`ToolCall`].
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCall {
    /// The name of the function to invoke.
    pub name: String,
    /// The function arguments serialized as a JSON object string.
    pub arguments: String,
}

/// A tool definition made available to the model during a completion request.
///
/// Providers that support tool use present these definitions to the model,
/// allowing it to emit structured [`ToolCall`] objects in assistant messages.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Tool {
    /// The tool's canonical name (used in function calls).
    pub name: String,
    /// Human-readable description of what the tool does.
    pub description: String,
    /// JSON Schema object describing the tool's input parameters.
    pub parameters: serde_json::Value,
}

